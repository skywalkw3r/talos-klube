#!/usr/bin/env bash
set -euo pipefail

## Generate Talos machine configs for the Proxmox cluster.
## Fallback path (`./bootstrap.sh shell`): tofu/talos.tf renders the same configs.
## Secrets land in talos/secrets.yaml and rendered configs in
## talos/clusterconfig/ — BOTH ARE GITIGNORED. Never commit them.
##
## Required environment:
#   export NODE_IPS='10.5.6.11,10.5.6.12,10.5.6.13'  # one per control plane node
#   export VIP='10.5.6.10'                           # shared control plane VIP
#   export GATEWAY='10.5.6.1'
##
## Optional environment (defaults shown):
#   export CLUSTER_NAME=klube-pmx
#   export TALOS_VERSION=v1.14.4
#   export PREFIX=24
#   export DNS_SERVERS='1.1.1.1,9.9.9.9'
#   export INSTALL_DISK=/dev/sda

CLUSTER_NAME=${CLUSTER_NAME:=klube-pmx}
TALOS_VERSION=${TALOS_VERSION:=v1.14.4}
PREFIX=${PREFIX:=24}
DNS_SERVERS=${DNS_SERVERS:=1.1.1.1,9.9.9.9}
INSTALL_DISK=${INSTALL_DISK:=/dev/sda}

: "${NODE_IPS:?set NODE_IPS, e.g. 10.5.6.11,10.5.6.12,10.5.6.13}"
: "${VIP:?set VIP, e.g. 10.5.6.10}"
: "${GATEWAY:?set GATEWAY, e.g. 10.5.6.1}"

TALOS_DIR=$(cd "$(dirname "$0")" && pwd)
OUT="${TALOS_DIR}/clusterconfig"
SECRETS="${TALOS_DIR}/secrets.yaml"
mkdir -p "${OUT}"

## Same deterministic schematic as proxmox.sh (qemu-guest-agent extension) —
## resolved and cached by its schematic_id helper, the single source.
SCHEMATIC_ID=$("${TALOS_DIR}/../proxmox.sh" schematic_id)

## Cluster secrets: generated once, never committed. This is what leaked
## in the old controlplane.yaml — keep it out of git forever.
if [ ! -f "${SECRETS}" ]; then
    talosctl gen secrets --output-file "${SECRETS}"
    echo "generated new cluster secrets at ${SECRETS} (gitignored)"
fi

# Disk encryption is emitted here as the ONLY source (never also in
# patches/cluster.yaml — key lists merge by appending and duplicate LUKS
# slots fail validation): TPM-sealed when SECUREBOOT=1, nodeID otherwise.
if [ "${SECUREBOOT:-1}" = "1" ]; then
    INSTALLER="installer-secureboot"
    KEY_TYPE="tpm"
else
    INSTALLER="installer"
    KEY_TYPE="nodeID"
fi
cat > "${OUT}/patch-encryption.yaml" <<EOF
apiVersion: v1alpha1
kind: VolumeConfig
name: STATE
encryption:
  provider: luks2
  keys:
    - ${KEY_TYPE}: {}
      slot: 0
---
apiVersion: v1alpha1
kind: VolumeConfig
name: EPHEMERAL
encryption:
  provider: luks2
  keys:
    - ${KEY_TYPE}: {}
      slot: 0
EOF
SB_PATCH=(--config-patch @"${OUT}/patch-encryption.yaml")

# Optional DNS name for the API endpoint (kept out of git — env only):
# added to both the kube-apiserver and Talos API cert SANs.
SAN_PATCH=()
if [ -n "${API_DNS_NAME:-}" ]; then
    cat > "${OUT}/patch-sans.yaml" <<EOF
machine:
  certSANs:
    - ${API_DNS_NAME}
---
apiVersion: v1alpha1
kind: KubeAPIServerConfig
certExtraSANs:
  - ${API_DNS_NAME}
EOF
    SAN_PATCH=(--config-patch @"${OUT}/patch-sans.yaml")
fi

# Upstream DNS servers (ResolverConfig document, merged with the hostDNS
# settings from patches/cluster.yaml)
dns_yaml=""
IFS=',' read -ra DNS <<< "${DNS_SERVERS}"
for d in "${DNS[@]}"; do dns_yaml="${dns_yaml}
  - address: ${d}"; done
cat > "${OUT}/patch-dns.yaml" <<EOF
apiVersion: v1alpha1
kind: ResolverConfig
nameservers:${dns_yaml}
EOF

talosctl gen config "${CLUSTER_NAME}" "https://${VIP}:6443" \
    --with-secrets "${SECRETS}" \
    --install-disk "${INSTALL_DISK}" \
    --install-image "factory.talos.dev/${INSTALLER}/${SCHEMATIC_ID}:${TALOS_VERSION}" \
    --config-patch @"${TALOS_DIR}/patches/cluster.yaml" \
    --config-patch @"${OUT}/patch-dns.yaml" \
    ${SB_PATCH[@]+"${SB_PATCH[@]}"} \
    ${SAN_PATCH[@]+"${SAN_PATCH[@]}"} \
    --with-docs=false --with-examples=false \
    --output-types controlplane,talosconfig \
    --output "${OUT}/" --force

## Per-node configs: static IP + VIP on the physical NIC
IFS=',' read -ra IPS <<< "${NODE_IPS}"
i=0
for ip in "${IPS[@]}"; do
    i=$((i + 1))
    name="${CLUSTER_NAME}-m${i}"
    # NOTE: no hostname here — the nocloud meta-data generated by Proxmox
    # names the node after the VM (${CLUSTER_NAME}-mN). Setting it in both
    # places makes Talos reject the config ("static hostname is already set").
    cat > "${OUT}/patch-${name}.yaml" <<EOF
machine:
  network:
    interfaces:
      - deviceSelector:
          physical: true
        dhcp: false
        addresses:
          - ${ip}/${PREFIX}
        routes:
          - network: 0.0.0.0/0
            gateway: ${GATEWAY}
        vip:
          ip: ${VIP}
EOF
    talosctl machineconfig patch "${OUT}/controlplane.yaml" \
        --patch @"${OUT}/patch-${name}.yaml" \
        --output "${OUT}/${name}.tmp.yaml"
    # Hostname lives in the HostnameConfig document (Talos >=1.12), which
    # gen config emits as `auto: stable` (random name). Setting it via
    # machine.network.hostname instead is rejected ("static hostname is
    # already set"), and auto+hostname can't coexist — so swap the field.
    sed "s/^auto: stable$/hostname: ${name}/" "${OUT}/${name}.tmp.yaml" > "${OUT}/${name}.yaml"
    rm -f "${OUT}/${name}.tmp.yaml"
    echo "rendered ${OUT}/${name}.yaml (${ip})"
done

## talosctl client config: talk to node IPs directly (never the VIP —
## the VIP depends on etcd, which is down exactly when you need talosctl)
talosctl --talosconfig "${OUT}/talosconfig" config endpoint "${IPS[@]}"
talosctl --talosconfig "${OUT}/talosconfig" config node "${IPS[0]}"
echo ""
echo "done. export TALOSCONFIG=${OUT}/talosconfig"
